from reportlab.lib.enums import TA_JUSTIFY
from pathlib import Path

DOCS_DIR = Path("/home/sakib/Desktop/Rag project/it-helpdesk-ai/backend/data/docs")
DOCS_DIR.mkdir(parents=True, exist_ok=True)

styles = getSampleStyleSheet()
H1 = ParagraphStyle("H1", parent=styles["Heading1"], fontSize=22, textColor=colors.HexColor("#1a237e"),
                    spaceAfter=8, spaceBefore=16, fontName="Helvetica-Bold")
H2 = ParagraphStyle("H2", parent=styles["Heading2"], fontSize=15, textColor=colors.HexColor("#283593"),
                    spaceAfter=6, spaceBefore=12, fontName="Helvetica-Bold")
H3 = ParagraphStyle("H3", parent=styles["Heading3"], fontSize=12, textColor=colors.HexColor("#37474f"),
                    spaceAfter=4, spaceBefore=8, fontName="Helvetica-Bold")
BODY = ParagraphStyle("BODY", parent=styles["Normal"], fontSize=10, leading=16,
                      alignment=TA_JUSTIFY, spaceAfter=6)
BULLET = ParagraphStyle("BULLET", parent=styles["Normal"], fontSize=10, leading=15,
                        leftIndent=18, spaceAfter=3)
CODE  = ParagraphStyle("CODE", parent=styles["Code"], fontSize=9, leading=13,
                       backColor=colors.HexColor("#f5f5f5"), leftIndent=12, rightIndent=12,
                       borderPadding=6, spaceAfter=8)
NOTE  = ParagraphStyle("NOTE", parent=styles["Normal"], fontSize=9, leading=14,
                       backColor=colors.HexColor("#e3f2fd"), leftIndent=12, rightIndent=12,
                       borderPadding=5, textColor=colors.HexColor("#0d47a1"), spaceAfter=8)

def hr(): return HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#b0bec5"), spaceAfter=8)
def sp(h=6): return Spacer(1, h)
def h1(t): return Paragraph(t, H1)
def h2(t): return Paragraph(t, H2)
def h3(t): return Paragraph(t, H3)
def p(t):  return Paragraph(t, BODY)
def b(t):  return Paragraph(f"• {t}", BULLET)
def code(t): return Paragraph(t, CODE)
def note(t): return Paragraph(f"INFO: {t}", NOTE)

def make_pdf(filename, title, content_fn):
    path = DOCS_DIR / filename
    doc  = SimpleDocTemplate(str(path), pagesize=A4,
                             leftMargin=2.2*cm, rightMargin=2.2*cm,
                             topMargin=2*cm, bottomMargin=2*cm)
    story = [h1(title), hr(), sp(4)]
    content_fn(story)
    doc.build(story)
    print(f"Created: {filename}")

